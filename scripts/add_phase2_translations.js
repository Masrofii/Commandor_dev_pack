const LANGS = ['en', 'ar', 'ru', 'fr', 'es', 'de', 'tr', 'pt', 'zh', 'hi', 'id', 'ur'];

const srcDir = path.join(__dirname, '../src/i18n/locales');
const webDir = path.join(__dirname, '../web/i18n');
const webLocalesPath = path.join(__dirname, '../web/lib/locales.json');

let webLocalesData = {};
if (fs.existsSync(webLocalesPath)) {
  webLocalesData = JSON.parse(fs.readFileSync(webLocalesPath, 'utf8'));
}

LANGS.forEach(lang => {
  const srcPath = path.join(srcDir, `${lang}.json`);
  const webPath = path.join(webDir, `${lang}.json`);

  let srcData = {};
  if (fs.existsSync(srcPath)) {
    srcData = JSON.parse(fs.readFileSync(srcPath, 'utf8'));
  }

  for (const [key, translations] of Object.entries(NEW_TRANSLATIONS)) {
    const val = translations[lang] || translations.en;
    srcData[key] = val;
  }

  fs.writeFileSync(srcPath, JSON.stringify(srcData, null, 2) + '\n');
  fs.writeFileSync(webPath, JSON.stringify(srcData, null, 2) + '\n');

  webLocalesData[lang] = srcData;
  console.log(`Updated ${lang} with ${Object.keys(NEW_TRANSLATIONS).length} new keys -> total ${Object.keys(srcData).length}`);
});

fs.writeFileSync(webLocalesPath, JSON.stringify(webLocalesData, null, 2) + '\n');
console.log('Successfully updated locales.json');
